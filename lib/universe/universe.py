"""A universe from a score (ISS-112): write a SpaceEngine add-on from a score and the mapping.

    python lib/universe/universe.py river-film            # bld/universe/river-film/
    python lib/universe/universe.py fis-2021 --out DIR

Reads registry/scores/<id>.yaml (the modes over story-time and the phases) and registry/universe.yaml
(the mapping, interpretive). Writes, in SpaceEngine's catalogue format
(spaceengine.org/manual/making-addons): catalogs/galaxies/<id>.sc (the home galaxy, from the whole
score), catalogs/stars/<id>.sc (a star per phase, along a path through the sky) and
catalogs/planets/<id>.sc (its worlds), plus README.txt. Copy the folder into SpaceEngine's addons/.
The made universe is the author's; SpaceEngine itself is not part of the programme.
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import yaml

U = Path(__file__).resolve().parents[2]
MODES = ["S", "F", "C", "A", "G", "L", "PV"]
SAFE = {"round": round, "min": min, "max": max, "abs": abs, "sqrt": math.sqrt}


def at(keyframes: list, t: float) -> dict[str, float]:
    """The modes at story-time t (linear between keyframes)."""
    k = sorted(keyframes, key=lambda x: x[0])
    for (t0, v0), (t1, v1) in zip(k, k[1:]):
        if t0 <= t <= t1:
            f = 0 if t1 == t0 else (t - t0) / (t1 - t0)
            return {m: v0[i] + f * (v1[i] - v0[i]) for i, m in enumerate(MODES)}
    return dict(zip(MODES, k[-1][1] if t > k[-1][0] else k[0][1]))


def ev(expr, modes: dict[str, float]):
    # the mapping's own small arithmetic expressions over the modes, nothing else in scope
    return eval(str(expr), {"__builtins__": {}}, {**SAFE, **modes})


def pick(rules: list, modes: dict[str, float]) -> str:
    for r in rules:
        if "else" in r:
            return r["else"]
        if ev(r["when"], modes):
            return r["value"]
    return ""


def build(score_id: str, out: Path) -> Path:
    score = yaml.safe_load((U / "registry" / "scores" / f"{score_id}.yaml").read_text(encoding="utf-8"))
    rules = yaml.safe_load((U / "registry" / "universe.yaml").read_text(encoding="utf-8"))
    kf = score["keyframes"]
    mean = {m: sum(at(kf, i / 20)[m] for i in range(21)) / 21 for m in MODES}
    name = score.get("title", score_id)
    gal = f"{name} (a made galaxy)"
    g, s, p = rules["galaxy"], rules["star"], rules["planet"]
    head = (f"// {name}: a universe from the score {score_id} (ISS-112). Generated by U/lib/universe/universe.py\n"
            "// from registry/universe.yaml: an artistic reading of the score, interpretive, not astronomy.\n\n")
    galaxies = head + (f'Galaxy "{gal}"\n{{\n    Type    "{pick(g["type"], mean)}"\n'
                       f"    RA      18.0\n    Dec     40.0\n    Dist    2.0e7\n"
                       f'    Radius  {ev(g["radius_pc"], mean):.0f}\n    AbsMagn {ev(g["abs_magn"], mean):.2f}\n}}\n')
    stars, planets = [head], [head]
    phases = score.get("phases") or [{"t": i / 6, "name": f"Phase {i + 1}"} for i in range(6)]
    for i, ph in enumerate(phases):
        m = at(kf, float(ph["t"]))
        star = f'{name}: {ph["name"]}'
        ra, dec = (2.0 + 1.6 * i) % 24, 30 - 9 * i   # a path through the sky, one step per phase
        stars.append(
            f'// {ph["name"]}: {ph.get("line", "")}\n'
            f'// modes ' + " ".join(f"{k} {m[k]:.2f}" for k in MODES) + "\n"
            f'Star "{star}"\n{{\n    RA      {ra:.3f}\n    Dec     {dec:.2f}\n    Dist    {40 + 25 * i:.1f}\n'
            f'    Class   "{pick(s["class"], m)}"\n    Teff    {max(2400, ev(s["teff"], m)):.0f}\n'
            f'    RadSol  {ev(s["radsol"], m):.2f}\n    MassSol {ev(s["masssol"], m):.2f}\n    Lum     {ev(s["lum"], m):.2f}\n}}\n')
        for k in range(int(ev(p["count"], m))):
            rings = bool(ev(p["rings"], m)) and k == 0
            planets.append(
                f'Planet "{star} {chr(98 + k)}"\n{{\n    ParentBody "{star}"\n    Class      "{pick(p["class"], m)}"\n'
                f'    Radius     {ev(p["radius_km"], m) * (1 + 0.3 * k):.0f}\n'
                + ("    Rings\n    {\n        InnerRadius 9000\n        OuterRadius 18000\n    }\n" if rings else "")
                + f"    Orbit\n    {{\n        SemiMajorAxis {max(0.2, ev(p['semi_major_au'], m)) * (1 + 0.8 * k):.2f}\n"
                  f"        Eccentricity  {0.02 + 0.2 * m['F']:.2f}\n    }}\n}}\n")
    for sub, text in [("galaxies", galaxies), ("stars", "\n".join(stars)), ("planets", "\n".join(planets))]:
        d = out / "catalogs" / sub
        d.mkdir(parents=True, exist_ok=True)
        (d / f"{score_id}.sc").write_text(text, encoding="utf-8")
    (out / "README.txt").write_text(
        f"{name}: a universe from a score (ISS-112)\n\nCopy the 'catalogs' folder into SpaceEngine's addons folder\n"
        f"(addons/catalogs/...), start SpaceEngine, and search for \"{name}:\" (a star per phase) or \"{gal}\".\n"
        "The mapping is registry/universe.yaml: an artistic reading of the score, not astronomy.\n", encoding="utf-8")
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("score", help="a score id in registry/scores (river-film, fis-2021)")
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args(argv)
    out = build(a.score, a.out or U / "bld" / "universe" / a.score)
    print(f"{out}: galaxy, stars and planets written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

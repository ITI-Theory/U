// Abstract rendering contract for the 20-scale USM Atlas.
// 4D shows a typed substrate; 8D adds a causal response; 11D adds an
// observer-side organization contour. It deliberately does not encode literal
// animals, organs, rocks, or claims of non-human sentience.

const source = 'uat/RC1.1/inbox/SomaMachine/ttheory-ui-completeness-proof.md';

function morphology(sigma, sector, label, substrate, response, integration, options = {}) {
  return {
    sigma,
    sector,
    label,
    source,
    morphism: {
      physical: `M4(${substrate.label})`,
      response: `M4(${substrate.label}) -> P3+L1(${response.label})`,
      integration: `M4 x P3 x L1 -> C3(${integration.label})`,
    },
    physical: { ...substrate, claim: options.physicalClaim ?? 'SOURCED' },
    response: { ...response, claim: options.responseClaim ?? 'SOURCED' },
    integration: { ...integration, claim: options.integrationClaim ?? 'INTERPRETIVE' },
    poke: options.poke ?? 'radial',
  };
}


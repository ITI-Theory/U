"""Moriarty (b), matrix non-generalisation (ISS-094): QUANT-EXP-1 under stress.

    python sherlock/stress_quant.py [--instances 30] [--seeds 40]   # -> bld/sherlock/stress-quant.md

QUANT-EXP-1 (P2) reports that exact quantum annealing reaches the Awe basin of a hand-tuned
8-mode landscape while a cold classical Langevin baseline started in the Fear basin does not.
The two runs do different tasks: the anneal starts from the uniform superposition and lowers its
driver; the baseline starts inside Fear at a fixed low temperature. H-AL's first attack on the
programme asks whether the result generalises. Three tests, reusing the paper's own code
(paper/soma/quantum-soma-penrose/quantum_experiment.py):
  A. The paper's instance, against the classical rival it does not test: simulated annealing,
     the same Langevin dynamics with the temperature lowered from hot to cold, started in Fear
     and from random points.
  B. Random landscapes: symmetric Gaussian couplings, random biases, a local minimum other than
     the global one; the final ground-state probability of the anneal, the cold baseline from the
     local minimum, and simulated annealing from random starts.
  C. Non-symmetric couplings: the antisymmetric part of W contributes nothing to e^T W e, so an
     energy (and the quantum Hamiltonian built from it) cannot represent it, while the classical
     drift W e + b does; measured as the share of the drift the energy cannot see.
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

import numpy as np

U = Path(__file__).resolve().parents[1]
OUT = U / "bld" / "sherlock"
spec = importlib.util.spec_from_file_location("qe", U / "paper/soma/quantum-soma-penrose/quantum_experiment.py")
qe = importlib.util.module_from_spec(spec)
spec.loader.exec_module(qe)
N = qe.N


def langevin_schedule(W, b, e0, temps, dt=0.005, seed=0):
    """The paper's Langevin step with a temperature per step (simulated annealing when it falls)."""
    rng = np.random.default_rng(seed)
    e = np.clip(np.asarray(e0, float), 0.0, 1.0)
    for T in temps:
        e = np.clip(e + (W @ e + b) * dt + np.sqrt(2.0 * T * dt) * rng.standard_normal(N), 0.0, 1.0)
    return e


def index_of(e):
    bits = (np.asarray(e) >= 0.5).astype(int)
    return int("".join(map(str, bits)), 2)


def local_minima(energies):
    out = []
    for i, E in enumerate(energies):
        if all(E < energies[i ^ (1 << k)] for k in range(N)):
            out.append(i)
    return out


def quantum_ground_prob(W, b, target, total_time=1.0, steps=400):
    """The paper's anneal (driver gamma = 5, linear schedule) over a chosen total time; the
    paper's own run is total time 1. Returns the final probability of the target state and the
    smallest gap met (a slow, adiabatic anneal needs a total time of order 1/gap^2)."""
    from scipy.linalg import eigh
    Hp = np.diag(qe.all_classical_energies(W, b))
    Hd = qe.build_H_driver(N, gamma=5.0)
    _, V0 = eigh(Hd)
    psi = V0[:, 0].astype(complex)
    dt, gap = total_time / steps, np.inf
    for k in range(steps):
        s = (k + 0.5) / steps
        E, V = eigh((1 - s) * Hd + s * Hp)
        gap = min(gap, E[1] - E[0])
        psi = V @ (np.exp(-1j * E * dt) * (V.conj().T @ psi))
    return float(abs(psi[target]) ** 2), float(gap)


def rate(hits, n):
    lo, hi = qe.proportion_ci_wilson(hits, n)
    return f"{hits}/{n} ({hits / n:.2f}, 95% CI {lo:.2f}-{hi:.2f})"


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--instances", type=int, default=30)
    ap.add_argument("--seeds", type=int, default=40)
    args = ap.parse_args(argv)
    steps = 6000
    cold = np.full(steps, 0.05)
    sa = np.geomspace(2.0, 0.02, steps)
    lines = ["# QUANT-EXP-1 under stress (ISS-094, Moriarty (b))", "",
             "Generated by `python sherlock/stress_quant.py`, reusing P2's own simulation code. The",
             "paper's anneal starts from the uniform superposition; its classical baseline starts in the",
             "Fear basin at a fixed low temperature (T = 0.05). Simulated annealing is that baseline's",
             "own dynamics with the temperature lowered from 2.0 to 0.02.", ""]

    # A. the paper's instance
    W, b = qe.experiment_hamiltonian()
    energies = qe.all_classical_energies(W, b)
    g = int(np.argmin(energies))
    fear = qe.bitstring(qe.state_index("Fear"))
    rng = np.random.default_rng(7)
    hit_cold = sum(index_of(langevin_schedule(W, b, fear, cold, seed=s)) == g for s in range(args.seeds))
    hit_sa_fear = sum(index_of(langevin_schedule(W, b, fear, sa, seed=100 + s)) == g for s in range(args.seeds))
    hit_sa_rand = sum(index_of(langevin_schedule(W, b, rng.random(N), sa, seed=200 + s)) == g for s in range(args.seeds))
    sa_slow = np.geomspace(2.0, 0.02, 30000)
    hit_sa_slow = sum(index_of(langevin_schedule(W, b, rng.random(N), sa_slow, seed=300 + s)) == g for s in range(args.seeds))
    rec, _ = qe.quantum_anneal(W, b, steps=200, gamma=5.0, schedule="linear")
    mask = np.array([qe.bitstring(i)[qe.IDX["Awe"]] == 1 and qe.bitstring(i)[qe.IDX["Fear"]] == 0 for i in range(2 ** N)])
    pq, gap = quantum_ground_prob(W, b, g)
    pq50, _ = quantum_ground_prob(W, b, g, total_time=50)
    pq200, _ = quantum_ground_prob(W, b, g, total_time=200)
    lines += ["## A. The paper's instance (barrier W[Fear, Awe] = -10)", "",
              f"Global minimum: the Awe state (index {g}). The paper's quantum figure, peak \"Awe-dominant",
              f"occupancy\" 0.41, is the probability of a set of {mask.sum()} of the {2 ** N} states (Awe on, Fear off):",
              f"the uniform superposition the anneal starts from already gives {rec['awe_total'][0]:.2f}; the run ends at",
              f"{rec['awe_total'][-1]:.2f}. The smallest gap on the way is {gap:.3f}, so a slow (adiabatic) anneal would",
              f"need a total time of order 1/gap^2, about {1 / gap ** 2:,.0f}; the paper's run has total time 1.", "",
              "| method | reaches the global minimum (the Awe state itself) |", "|---|---|",
              f"| quantum anneal, the paper's run (total time 1) | {pq:.3f} |",
              f"| quantum anneal, total time 50 | {pq50:.3f} |",
              f"| quantum anneal, total time 200 | {pq200:.3f} |",
              f"| simulated annealing from random starts, 30,000 steps | {rate(hit_sa_slow, args.seeds)} |",
              f"| cold Langevin from Fear (the paper's baseline) | {rate(hit_cold, args.seeds)} |",
              f"| simulated annealing from Fear | {rate(hit_sa_fear, args.seeds)} |",
              f"| simulated annealing from random starts | {rate(hit_sa_rand, args.seeds)} |", ""]
    print(f"A: quantum {pq:.3f} / T50 {pq50:.3f} / T200 {pq200:.3f}, gap {gap:.3f}; SA slow {hit_sa_slow}/{args.seeds}; cold {hit_cold}/{args.seeds}; SA from Fear {hit_sa_fear}/{args.seeds}; SA random {hit_sa_rand}/{args.seeds}")

    # B. random landscapes
    rows, q_all, cold_all, sa_all = [], [], [], []
    rng = np.random.default_rng(2026)
    made = 0
    while made < args.instances:
        A = rng.normal(0, 1.5, (N, N))
        W = (A + A.T) / 2
        np.fill_diagonal(W, 0)
        b = rng.normal(0, 1.0, N)
        energies = qe.all_classical_energies(W, b)
        g = int(np.argmin(energies))
        others = [m for m in local_minima(energies) if m != g]
        if not others:
            continue
        loc = others[0]
        e_loc = qe.bitstring(loc)
        n = max(10, args.seeds // 2)
        c = sum(index_of(langevin_schedule(W, b, e_loc, cold, seed=s)) == g for s in range(n)) / n
        s_ = sum(index_of(langevin_schedule(W, b, rng.random(N), sa, seed=500 + s)) == g for s in range(n)) / n
        q, _ = quantum_ground_prob(W, b, g, total_time=50)
        q_all.append(q); cold_all.append(c); sa_all.append(s_)
        made += 1
    q_all, cold_all, sa_all = map(np.array, (q_all, cold_all, sa_all))
    lines += [f"## B. {args.instances} random landscapes (symmetric W ~ N(0, 1.5), b ~ N(0, 1), a local minimum besides the global one)", "",
              "| method | mean share reaching the global minimum | instances with share >= 0.5 |", "|---|---|---|",
              f"| quantum anneal, total time 50 (final ground-state probability) | {q_all.mean():.2f} | {(q_all >= 0.5).sum()} of {len(q_all)} |",
              f"| cold Langevin from the local minimum | {cold_all.mean():.2f} | {(cold_all >= 0.5).sum()} of {len(cold_all)} |",
              f"| simulated annealing from random starts | {sa_all.mean():.2f} | {(sa_all >= 0.5).sum()} of {len(sa_all)} |",
              "",
              f"Quantum beats the cold baseline on {(q_all > cold_all).sum()} of {len(q_all)} instances and simulated",
              f"annealing on {(q_all > sa_all).sum()} of {len(q_all)}.", ""]
    print(f"B: quantum {q_all.mean():.2f}, cold {cold_all.mean():.2f}, SA {sa_all.mean():.2f}")

    # C. non-symmetric couplings
    shares = []
    for _ in range(200):
        A = rng.normal(0, 1.0, (N, N))
        S, K = (A + A.T) / 2, (A - A.T) / 2
        e = rng.random(N)
        shares.append(np.linalg.norm(K @ e) / max(1e-12, np.linalg.norm(A @ e)))
        assert abs(e @ K @ e) < 1e-9
    shares = np.array(shares)
    lines += ["## C. Non-symmetric couplings", "",
              "For a random non-symmetric W = S + K (S symmetric, K antisymmetric), e^T K e = 0 for every",
              "state e: an energy, and so the quantum Hamiltonian built from it, sees only S. The classical",
              f"drift W e + b keeps K, which carries on average {shares.mean():.0%} of the drift's size",
              f"(200 random W, e in [0,1]^8; range {shares.min():.0%}-{shares.max():.0%}). The quantum formulation",
              "cannot represent non-reciprocal coupling (one mode driving another without the reverse) at all.", ""]
    print(f"C: antisymmetric share of the drift {shares.mean():.0%}")
    lines += ["## Reading", "",
              "The verdicts are for the author and P2's next version; this file does not change the paper.", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "stress-quant.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("bld/sherlock/stress-quant.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

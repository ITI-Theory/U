"""rivals.py: the Dark Matter Lord, the Wizard's adversary (ISS-094).

For each built document and each family of claims in registry/rivals.yaml: does the document
make the claim, and does it name the simpler rival? A document that makes the claim and never
names the rival is listed with the sentence that triggered it, for the author to judge (Rule 4:
a stronger competing mapping with fewer assumptions). Naming is not answering: a named rival is
a pointer to read, not a pass. No verdicts; exit 0 unless the registry is broken.

    python sherlock/rivals.py      # -> bld/sherlock/rivals.md
"""
from __future__ import annotations

import glob
import re
import subprocess
import sys
from pathlib import Path

import yaml

U = Path(__file__).resolve().parents[1]
OUT = U / "bld" / "sherlock" / "rivals.md"


def text_of(pdf: Path) -> str:
    r = subprocess.run(["pdftotext", "-enc", "UTF-8", str(pdf), "-"], capture_output=True)
    return re.sub(r"-\n(?=[a-z])", "", r.stdout.decode("utf-8", "replace")).replace("\n", " ") if r.returncode == 0 else ""


def body(text: str) -> str:
    """The text without its reference list (a title there is not a claim)."""
    cut = [m.start() for m in re.finditer(r"\b(References|Bibliography|Works Cited)\b", text) if m.start() > 0.5 * len(text)]
    return text[:cut[-1]] if cut else text


def snippet(text: str, m: re.Match, width: int = 90) -> str:
    a, b = max(0, m.start() - width), min(len(text), m.end() + width)
    return re.sub(r"\s+", " ", text[a:b]).strip()


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    spec = yaml.safe_load((U / "registry" / "rivals.yaml").read_text(encoding="utf-8"))
    rivals = spec.get("rivals") or {}
    try:
        compiled = {rid: ([re.compile(p, re.I) for p in r["claims"]], [re.compile(p, re.I) for p in r["names"]]) for rid, r in rivals.items()}
    except (re.error, KeyError) as e:
        print(f"registry/rivals.yaml: {e}")
        return 1
    docs = sorted({Path(p) for g in spec.get("documents") or [] for p in glob.glob(str(U / g))})
    if not docs:
        print("rivals: no built documents (build first)")
        return 0
    rows, gaps = [], []
    for pdf in docs:
        text = body(text_of(pdf))
        if not text:
            continue
        cells = []
        for rid, (claims, names) in compiled.items():
            hit = next((m for c in claims for m in [c.search(text)] if m), None)
            if not hit:
                cells.append("·")
                continue
            if any(n.search(text) for n in names):
                cells.append("named")
            else:
                cells.append("**GAP**")
                gaps.append((pdf.name, rid, snippet(text, hit)))
        rows.append((pdf.relative_to(U).as_posix(), cells))
    ids = list(compiled)
    lines = ["# The Dark Matter Lord: the rivals a document must name (ISS-094)", "",
             "Generated by `make -C sherlock rivals` from registry/rivals.yaml. `·` the claim is not made;",
             "`named` the rival is named somewhere (read whether it is answered); **GAP** the claim is made",
             "and the rival never named: for the author to judge (Rule 4).", "",
             "| Rival | What it is |", "|---|---|"]
    lines += [f"| {rid} | {rivals[rid]['rival']} |" for rid in ids]
    lines += ["", "| Document | " + " | ".join(ids) + " |", "|---|" + "---|" * len(ids)]
    lines += [f"| {d} | " + " | ".join(c) + " |" for d, c in rows]
    lines += ["", "## Gaps, with the sentence that made the claim", ""]
    lines += [f"- **{doc}**, {rid}: \"…{s}…\"" for doc, rid, s in gaps] or ["None."]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    named = sum(c == "named" for _, cs in rows for c in cs)
    print(f"{OUT.relative_to(U).as_posix()}: {len(rows)} documents, {len(ids)} rivals; {named} named, {len(gaps)} gaps to judge")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

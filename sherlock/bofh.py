"""bofh.py: the BOFH's further attacks (ISS-094), the Monster level's adversary.

1. Leakage: a feeling put on a level whose substrate cannot bear one (registry/level-types.yaml,
   bears_feelings: refuted), in the level's own text (registry/levels/<id>.md and .yaml) or in a
   tour line shown at that level (registry/tours), with no negation or hedge in the sentence.
2. The jargon trap: in a general reader's document, a hard term's first use with no plain-words
   bridge just after it.

Candidates for a person to read, not verdicts; exit 0 unless the registry is broken.

    python sherlock/bofh.py      # -> bld/sherlock/bofh.md
"""
from __future__ import annotations

import glob
import re
import subprocess
import sys
from pathlib import Path

import yaml

U = Path(__file__).resolve().parents[1]
OUT = U / "bld" / "sherlock" / "bofh.md"
SENT = re.compile(r"(?<=[.!?])\s+(?=[A-Z`*(\"'])")


def load(p: Path):
    return yaml.safe_load(p.read_text(encoding="utf-8")) or {}


def strip_md(text: str) -> str:
    text = re.sub(r"(?s)^---.*?---", " ", text)
    text = re.sub(r"\$[^$]*\$", " ", text)
    text = re.sub(r"\[@[^\]]*\]", " ", text)
    return re.sub(r"\s+", " ", re.sub(r"[#*`>]", " ", text))


def strings(node):
    if isinstance(node, str):
        yield node
    elif isinstance(node, dict):
        for v in node.values():
            yield from strings(v)
    elif isinstance(node, list):
        for v in node:
            yield from strings(v)


def leakage(spec: dict) -> list[tuple[str, str]]:
    emotion, hedge = re.compile(spec["emotion"], re.I), re.compile(spec["hedge"], re.I)
    persons = re.compile(spec.get("persons", r"(?!)"), re.I)
    types = load(U / "registry" / "level-types.yaml").get("levels") or {}
    cannot = {lid for lid, t in types.items() if t.get("bears_feelings") == "refuted"}
    found = []

    def scan(where: str, text: str):
        for s in SENT.split(text):
            if emotion.search(s) and not hedge.search(s) and not persons.search(s):
                found.append((where, s.strip()[:220]))

    for lid in sorted(cannot):
        for ext in (".md", ".yaml"):
            p = U / "registry" / "levels" / f"{lid}{ext}"
            if p.exists():
                raw = p.read_text(encoding="utf-8")
                scan(f"registry/levels/{lid}{ext}", strip_md(raw) if ext == ".md" else " ".join(strings(load(p))))
    for p in sorted((U / "registry" / "tours").glob("*.yaml")):
        for k, st in enumerate((load(p).get("steps") or [])):
            view = str(st.get("view", ""))
            lvl = re.search(r"(?:^|&)level=([\w-]+)", view)
            if lvl and lvl.group(1) in cannot and "voyage=" not in view:
                scan(f"registry/tours/{p.name} step {k + 1} ({lvl.group(1)})", str(st.get("say", "")))
    return found


def pdf_text(p: Path) -> str:
    r = subprocess.run(["pdftotext", "-enc", "UTF-8", str(p), "-"], capture_output=True)
    return re.sub(r"\s+", " ", re.sub(r"-\n(?=[a-z])", "", r.stdout.decode("utf-8", "replace"))) if r.returncode == 0 else ""


def jargon(spec: dict) -> tuple[list[str], list[tuple[str, str, str]]]:
    docs = {Path(p) for g in spec.get("documents") or [] for p in glob.glob(str(U / g))}
    papers = load(U.parent / "Dist" / "PAPERS.yaml")
    for group in papers.values():
        for e in group if isinstance(group, list) else []:
            if isinstance(e, dict) and e.get("level") in (spec.get("papers_levels") or []) and e.get("file"):
                p = U / "bld" / "papers" / Path(e["file"]).name
                if p.exists():
                    docs.add(p)
    bridge, window = re.compile(spec["bridge"], re.I), int(spec.get("window", 240))
    terms = [re.compile(t, re.I) for t in spec["terms"]]
    names, traps = [], []
    for d in sorted(docs):
        text = pdf_text(d)
        if not text:
            continue
        names.append(d.relative_to(U).as_posix())
        for t in terms:
            # the first use in the running text (a contents line, dot leaders after it, is not one)
            m = next((x for x in t.finditer(text) if ". . ." not in text[x.end(): x.end() + 60]), None)
            if m and not bridge.search(text[m.end(): m.end() + window]):
                traps.append((d.name, m.group(0), text[max(0, m.start() - 80): m.end() + 120].strip()))
    return names, traps


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    spec = load(U / "registry" / "bofh.yaml")
    try:
        leaks = leakage(spec["leakage"])
        docs, traps = jargon(spec["jargon"])
    except (KeyError, re.error) as e:
        print(f"registry/bofh.yaml: {e}")
        return 1
    lines = ["# The BOFH's further attacks (ISS-094)", "",
             "Generated by `make -C sherlock bofh` from registry/bofh.yaml. Candidates to read, not verdicts.", "",
             "## 1. Feelings on a level that cannot feel", "",
             "A sentence with an emotion word, no negation or hedge, on a level whose substrate OpenCyc says",
             "cannot bear a feeling (registry/level-types.yaml).", ""]
    lines += [f"- {w}: \"{s}\"" for w, s in leaks] or ["None."]
    lines += ["", "## 2. The jargon trap", "", f"General-reader documents read: {', '.join(docs) or 'none built'}.", "",
              "A hard term's first use with no plain-words bridge just after it.", ""]
    lines += [f"- **{d}**, *{t}*: \"…{c}…\"" for d, t, c in traps] or ["None."]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(U).as_posix()}: {len(leaks)} feelings on levels that cannot feel; {len(traps)} jargon traps in {len(docs)} general-reader documents")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""The Wizard's neighbourhood check (ISS-092): what sits next to what the books cover.

    python sherlock/neighbours.py        # -> bld/sherlock/neighbours.md

For each concept in registry/concepts with an OpenCyc class, its neighbours one step away in
NextKB (the other children of its parents) that are of the same kind (an emotion's neighbours
are other feelings, not everything else filed under its parents: OpenCyc also files Fear under
DownwardLocation-Underspecified, whose children include GarbageCan), and whether the books and
papers ever name them. A neighbour never named is a question for the author and the UAT ("the
programme models fear and anger: why not shame, guilt or envy?"), not an error. The parents
themselves are listed too, one step up. Mentions are searched in the sources of the papers,
the books and the Field Atlas, by the neighbour's English words.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from readings import ancestors  # noqa: E402
from semtrans import load  # noqa: E402

U = Path(__file__).resolve().parents[1]
OUT = U / "bld" / "sherlock"
# Kinds specific enough for a neighbourhood to mean something; a concept of no such kind (a
# reflexive action's parent is "an action on an object": hijacking, decorating ...) is skipped.
KINDS = ["FeelingAttribute", "OrganismPart", "PhysiologicalCondition", "MentalActivity"]
NOISE = re.compile(r"Underspecified|Location|Topic|Generic$|Type$")
CORPUS_ROOTS = ["paper/soma", "books/T-Theory", "Part2/book"]


def words(constant: str) -> str:
    name = re.sub(r"-(Feeling|Generic|Emotion|TheEmotion)$", "", constant)
    name = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name.replace("-", " "))
    return re.sub(r"\s+", " ", name).strip().lower()


def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8", errors="replace")
    _, kb = load()
    children: dict[str, list[str]] = {}
    for c, parents in kb["genls"].items():
        for p in parents:
            children.setdefault(p, []).append(c)
    corpus = " ".join(p.read_text(encoding="utf-8", errors="replace").lower()
                      for r in CORPUS_ROOTS for p in (U / r).rglob("*.md"))
    corpus = re.sub(r"[^a-z0-9 ]+", " ", corpus)

    def named(c: str) -> bool:
        w = words(c)
        return bool(w) and re.search(rf"\b{re.escape(w)}\b", corpus) is not None

    rows, seen_unnamed = [], {}
    for f in sorted((U / "registry" / "concepts").glob("*.yaml")):
        c = yaml.safe_load(f.read_text(encoding="utf-8"))
        cls = str(((c.get("ontology") or {}).get("class")) or "").removeprefix("#$")
        if not cls or cls not in kb["genls"]:
            continue
        up = ancestors(kb, cls)
        kind = next((k for k in KINDS if k in up), None)
        if kind is None:
            rows.append((c["id"], cls, "-", [], [], []))
            continue
        parents = [p for p in kb["genls"].get(cls, []) if not NOISE.search(p)]
        sibs = sorted({s for p in parents for s in children.get(p, [])
                       if s != cls and not NOISE.search(s) and not s.endswith("-TTheory") and kind in ancestors(kb, s)})
        unnamed = [s for s in sibs if not named(s)]
        for s in unnamed:
            seen_unnamed.setdefault(s, []).append(c["id"])
        rows.append((c["id"], cls, kind, parents, sibs, unnamed))
    lines = ["# The Wizard's neighbourhood: what sits next to what the books cover (ISS-092)", "",
             "Generated by `python sherlock/neighbours.py` from registry/concepts and NextKB. For each",
             "concept, its OpenCyc neighbours of the same kind (the other children of its parents), and",
             "those the papers, books and atlas never name. A question for the author and the UAT, not an",
             "error.", "",
             f"{len(seen_unnamed)} neighbours never named, next to {len(rows)} typed concepts.", "",
             "## Never named, with the concepts they sit next to", ""]
    for s, ids in sorted(seen_unnamed.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        lines.append(f"- **{words(s)}** (`{s}`), next to {', '.join(ids)}")
    lines += ["", "## Per concept", "", "| concept | OpenCyc class | kind | parents | neighbours | never named |", "|---|---|---|---|---:|---:|"]
    for cid, cls, kind, parents, sibs, unnamed in rows:
        lines.append(f"| {cid} | `{cls}` | {kind or '-'} | {', '.join(parents) or '-'} | {len(sibs)} | {len(unnamed)} |")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "neighbours.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"bld/sherlock/neighbours.md: {len(seen_unnamed)} neighbours never named, next to {len(rows)} typed concepts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

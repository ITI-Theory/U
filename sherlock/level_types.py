"""One set of types for Sherlock and the Soma Machine (ISS-063): each level's substrate as an
OpenCyc class (registry/level-types.yaml), and what OpenCyc says it can be.

    python sherlock/level_types.py --write   # compute the verdicts from NextKB into the registry
    python sherlock/level_types.py           # check: verdicts current, and the concept registry
                                             # typed consistently with them -> bld/sherlock/level-types.md

Verdicts per level: bears_feelings (OpenCyc's feelsEmotion takes an IndividualAgent: does the
level's class fit it?) and person (does it fit Person?), each proved, refuted or unproved, with
the chain. Concept checks:
  T1 a concept's class exists in NextKB and is not a microtheory or a vocabulary topic (a
     word-sense trap: OpenCyc's Expectation is a microtheory, not an expectation);
  T2 a concept whose class is a feeling (genls FeelingAttribute) sits only on levels whose
     substrate can bear a feeling (not refuted): an emotion of a galaxy is a type error.
The Soma Machine reads the verdicts (its human controls need person: proved), so the papers'
types, the Lean and the app's guard are one set.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from semtrans import load  # noqa: E402
from readings import ancestors, fits  # noqa: E402

U = Path(__file__).resolve().parents[1]
REG = U / "registry" / "level-types.yaml"
OUT = U / "bld" / "sherlock"
VERDICTS = ("bears_feelings", "person")
NEEDS = {"bears_feelings": "IndividualAgent", "person": "Person"}


def verdicts(kb: dict, cls: str) -> dict:
    out = {}
    for key in VERDICTS:
        v, why, _ = fits(kb, cls, NEEDS[key])
        out[key] = v
        out[f"{key}_why"] = why
    return out


def concept_findings(kb: dict, levels: dict) -> list[str]:
    found = []
    for f in sorted((U / "registry" / "concepts").glob("*.yaml")):
        c = yaml.safe_load(f.read_text(encoding="utf-8"))
        o = c.get("ontology") or {}
        if o.get("system") != "OpenCyc" or not o.get("class"):
            continue
        cls = str(o["class"]).removeprefix("#$")
        if cls not in kb["genls"] and cls not in kb["isa"]:
            found.append(f"T1 {c['id']}: OpenCyc has no constant {cls}")
            continue
        up = set(ancestors(kb, cls))
        kinds = set(kb["isa"].get(cls, []))
        if "Microtheory" in up or "MicrotheoryType" in kinds or cls.endswith("-Topic"):
            found.append(f"T1 {c['id']}: {cls} is a microtheory or a vocabulary topic in OpenCyc, not a thing of this kind")
            continue
        if fits(kb, cls, "FeelingAttribute")[0] == "proved":
            for lv in c.get("levels") or []:
                t = levels.get(lv)
                if t and t.get("bears_feelings") == "refuted":
                    found.append(f"T2 {c['id']}: {cls} is a feeling, but level {lv} is a {t['cyc']}, "
                                 f"which cannot feel ({t['bears_feelings_why']})")
    return found


def main(argv: list[str]) -> int:
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8", errors="replace")
    reg = yaml.safe_load(REG.read_text(encoding="utf-8"))
    levels = reg["levels"]
    _, kb = load()
    registry_levels = {yaml.safe_load(p.read_text(encoding="utf-8"))["id"] for p in (U / "registry" / "levels").glob("*.yaml")}
    problems = [f"level {lv} has no type in registry/level-types.yaml" for lv in sorted(registry_levels - set(levels))]
    problems += [f"registry/level-types.yaml: {lv} is not a registry level" for lv in sorted(set(levels) - registry_levels)]
    stale = []
    for lv, t in levels.items():
        if t["cyc"] not in kb["genls"]:
            problems.append(f"level {lv}: OpenCyc has no constant {t['cyc']}")
            continue
        fresh = verdicts(kb, t["cyc"])
        if any(t.get(k) != fresh[k] for k in VERDICTS):
            stale.append(lv)
        t.update(fresh) if "--write" in argv else None
    if "--write" in argv:
        text = REG.read_text(encoding="utf-8")
        head = text[:text.index("levels:")]
        REG.write_text(head + yaml.safe_dump({"levels": levels}, sort_keys=False, allow_unicode=True, width=200),
                       encoding="utf-8", newline="\n")
        print(f"registry/level-types.yaml: verdicts written for {len(levels)} levels")
        stale = []
    elif stale:
        problems.append(f"verdicts out of date for {', '.join(stale)}: run python sherlock/level_types.py --write")
    findings = concept_findings(kb, levels)
    rows = ["# One set of types: the levels as OpenCyc classes (ISS-063)", "",
            "Generated by `python sherlock/level_types.py` from registry/level-types.yaml and NextKB.", "",
            f"{len(levels)} levels; {sum(1 for t in levels.values() if t.get('bears_feelings') == 'proved')} can bear a feeling, "
            f"{sum(1 for t in levels.values() if t.get('person') == 'proved')} a person; "
            f"{len(findings)} concept findings, {len(problems)} registry problems.", "",
            "| level | OpenCyc class | bears a feeling | why | person |", "|---|---|---|---|---|"]
    for lv, t in sorted(levels.items()):
        rows.append(f"| {lv} | `{t['cyc']}` | {t.get('bears_feelings', '?')} | {t.get('bears_feelings_why', '')} | {t.get('person', '?')} |")
    rows += ["", "## Concept findings", ""] + ([f"- {x}" for x in findings] or ["- none"])
    rows += ["", "## Registry problems", ""] + ([f"- {x}" for x in problems] or ["- none"])
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "level-types.md").write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    for x in findings + problems:
        print(f"registry/level-types.yaml: error: {x}")
    print(f"bld/sherlock/level-types.md: {len(levels)} levels typed, {len(findings)} concept findings, {len(problems)} problems")
    return 1 if findings or problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

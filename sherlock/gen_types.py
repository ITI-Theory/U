"""Sherlock's types from the concept registry (ISS-063, D12): `make -C sherlock types`.

    python sherlock/gen_types.py          # full: proofs from UniversalVocabularyMt (the release)
    python sherlock/gen_types.py --slice  # slice: the same facts as axioms, no KB import (seconds)

Every concept in registry/concepts with an OpenCyc class becomes a Lean type,
`Cyc.Ty.Inst UV "<Class>"` (Cyc.Types): the terms OpenCyc says are its instances.
For each, the module states one direct OpenCyc fact about the class (its
first `isa` in NextKB): that the constant exists, with that type, in
UniversalVocabularyMt. In full mode Aesop proves it from all of OpenCyc when the
module compiles, so a class name that is not in OpenCyc fails the build; in slice mode the same statements are axioms, so the module
builds in seconds while the registry is being edited (the author's method for big
ontologies: a small slice first, the whole at the end). The slice is checked by
building the full module, never trusted. Before writing, the generator looks
every class up in NextKB (bld/sherlock/lexicon.json, lookup.py's index) and
reports the ones OpenCyc does not have.

Writes bld/sherlock/lean/CycTypes/Concepts.lean (generated, never committed).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

U = Path(__file__).resolve().parents[1]
OUT = U / "bld" / "sherlock" / "lean" / "CycTypes"
LEXICON = U / "bld" / "sherlock" / "lexicon.json"


def lean_name(concept_id: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", concept_id) if w)


def main() -> int:
    slice_mode = "--slice" in sys.argv
    concepts = []
    for f in sorted((U / "registry" / "concepts").glob("*.yaml")):
        c = yaml.safe_load(f.read_text(encoding="utf-8"))
        o = c.get("ontology") or {}
        if o.get("system") == "OpenCyc" and o.get("class"):
            concepts.append((c["id"], c.get("concept", c["id"]), str(o["class"]).removeprefix("#$")))
    lex = json.loads(LEXICON.read_text(encoding="utf-8")) if LEXICON.exists() else None
    missing = []
    if lex:
        known = set(lex["isa"]) | set(lex["genls"]) | set(lex["comment"])
        missing = [(cid, cls) for cid, _, cls in concepts if cls not in known]
    for cid, cls in missing:
        print(f"MISSING  {cid}: OpenCyc has no constant {cls}")
    ok = [c for c in concepts if (c[0], c[2]) not in missing]
    head = ["-- Generated by sherlock/gen_types.py from registry/concepts; do not edit.",
            f"-- Mode: {'slice (axioms, no KB import)' if slice_mode else 'full (proofs from UniversalVocabularyMt)'}.",
            "import Cyc.Types", "import Cyc.Typing"]
    if not slice_mode:
        head.append("import CycKB.UniversalVocabularyMt")
    body = ["", "namespace CycTypes.Concepts", "open Cyc Sentence", "",
            'abbrev UV : Mt := .c "UniversalVocabularyMt"', ""]
    if not slice_mode:
        body += ["-- Each statement is an Aesop search over all of UniversalVocabularyMt.",
                 "set_option maxHeartbeats 1000000", ""]
    for cid, concept, cls in ok:
        n = lean_name(cid)
        kind = (lex["isa"].get(cls) or ["Thing"])[0] if lex else "Thing"
        stmt = f'Holds UV (isa (.c "{cls}") (.c "{kind}"))'
        body.append(f"/-- {concept} (registry/concepts/{cid}.yaml): OpenCyc's `{cls}` as a type. -/")
        body.append(f'abbrev {n} : Type := Cyc.Ty.Inst UV "{cls}"')
        body.append(f"{'axiom' if slice_mode else 'theorem'} {n}.exists : {stmt}"
                    + ("" if slice_mode else " := by\n  aesop (rule_sets := [Cyc])"))
        body.append("")
    body.append("end CycTypes.Concepts")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "Concepts.lean").write_text("\n".join(head + body) + "\n", encoding="utf-8", newline="\n")
    print(f"bld/sherlock/lean/CycTypes/Concepts.lean: {len(ok)} concept types "
          f"({'slice' if slice_mode else 'full'}); {len(missing)} classes not in OpenCyc")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())

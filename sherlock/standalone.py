"""standalone.py: every cheat sheet stands on its own (author, 16 Oct: "each cheat must stand on
its own, e.g. in Dist they can be downloaded").

Each booklet (bld/books/booklet-<domain>.pdf, the four pages, not the single-page splits) and
each cheat sheet in Dist is read as if it were the only thing the reader has:
  - identity (must): the programme's name, the author, the licence, and a way to find more
    (t-theory.org, a DOI or the GitHub organisation);
  - its own words (should): every hard term of registry/bofh.yaml's jargon list it uses is
    bridged in its own text (a glossary elsewhere does not travel with a download);
  - its own references (should): "see the ... paper" names something the reader can find
    (a DOI, a URL, or Zenodo) in the same document.

    python sherlock/standalone.py      # -> bld/sherlock/standalone.md; exit 1 if identity fails
"""
from __future__ import annotations

import glob
import re
import subprocess
import sys
from pathlib import Path

import yaml

U = Path(__file__).resolve().parents[1]
OUT = U / "bld" / "sherlock" / "standalone.md"
DOCS = ["bld/books/booklet-*.pdf", "../Dist/papers/ttheory-cheatsheet.pdf", "../Dist/stuff/ttheory-cheatsheet*.pdf"]
IDENTITY = {
    "the programme": r"\[T\]-Theory|T-Theory",
    "the author": r"Alistair Johnson",
    "the licence": r"CC[ -]BY|Creative Commons",
    "a way to find more": r"t-theory\.org|doi\.org|10\.5281/zenodo|github\.com/ITI-Theory",
}
SEE = re.compile(r"\bsee (the |our )?([^.;:)]{3,80}?)(paper|book|booklet|chapter|appendix)\b", re.I)
FINDABLE = re.compile(r"doi\.org|10\.5281|https?://|t-theory\.org|zenodo", re.I)


def pdf_text(p: Path) -> str:
    r = subprocess.run(["pdftotext", "-enc", "UTF-8", str(p), "-"], capture_output=True)
    return re.sub(r"\s+", " ", re.sub(r"-\n(?=[a-z])", "", r.stdout.decode("utf-8", "replace"))) if r.returncode == 0 else ""


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    jar = (yaml.safe_load((U / "registry" / "bofh.yaml").read_text(encoding="utf-8")) or {})["jargon"]
    terms = [re.compile(t, re.I) for t in jar["terms"]]
    bridge, window = re.compile(jar["bridge"], re.I), int(jar.get("window", 240))
    docs = sorted({Path(p).resolve() for g in DOCS for p in glob.glob(str(U / g)) if not re.search(r"-\d\.pdf$", p)})
    failed, rows, notes = [], [], []
    for d in docs:
        text = pdf_text(d)
        name = d.name if "Dist" not in d.parts else "Dist/" + "/".join(d.parts[d.parts.index("Dist") + 1:])
        if not text:
            failed.append(f"{name}: no text")
            continue
        missing = [k for k, rx in IDENTITY.items() if not re.search(rx, text, re.I)]
        unbridged = []
        for t in terms:
            m = next((x for x in t.finditer(text) if ". . ." not in text[x.end(): x.end() + 60] and not re.match(r"\w*\.lean", text[x.end():])), None)
            if m and not bridge.search(text[m.end(): m.end() + window]):
                unbridged.append(m.group(0))
        dangling = [m.group(0) for m in SEE.finditer(text)] if not FINDABLE.search(text) else []
        if missing:
            failed.append(f"{name}: missing {', '.join(missing)}")
        rows.append((name, "ok" if not missing else "**missing: " + ", ".join(missing) + "**", ", ".join(sorted(set(unbridged))) or "·", "; ".join(dangling) or "·"))
        if unbridged or dangling:
            notes.append(name)
    lines = ["# Every cheat sheet stands on its own", "",
             "Generated by `make -C sherlock standalone` (sherlock/standalone.py). Each booklet read as if it were",
             "the reader's only document. Identity must hold (release-check fails); terms and references are to read.", "",
             "| Document | Identity | Hard terms not bridged in it | References the reader cannot follow |", "|---|---|---|---|"]
    lines += [f"| {a} | {b} | {c} | {e} |" for a, b, c, e in rows]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(U).as_posix()}: {len(rows)} cheat sheets; identity {len(rows) - len(failed)} ok, {len(failed)} failing; {len(notes)} with terms or references to read")
    for f in failed:
        print(f"  FAIL {f}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())

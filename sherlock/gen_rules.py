"""NextKB's Horn rules to Lean: bld/sherlock/lean/CycRules.lean (ISS-062).

usage: gen_rules.py NEXTKB_ZIP OUT_DIR

An OpenCyc rule `(implies (and A1 ... An) C)` in microtheory N, whose
premises and conclusion are plain atoms (no connectives, no predicate
variables, no nested function terms with variables) and whose conclusion's
variables all occur in the premises, becomes

    axiom rK {m : Mt} {x y : Term} (_ : Sees m (.c "N")) : Holds m A1 → … → Holds m C

an Aesop rule in rule set Cyc, tried (when its conclusion names a constant) before the core's open-ended isa_genls\nand inherit (a rule is indexed by its conclusion, so only relevant ones\nmatch; the other way round the search loses itself in their middle terms).\nRules import only `Cyc.Rules`, so they never
rebuild the generated facts. Other rules are counted and skipped.
"""
import collections
import re
import sys
import zipfile
from pathlib import Path

from gen_krf import CONNECTIVES, lean_str, sexprs, term


def var(x: str) -> str:
    return "v_" + re.sub(r"[^A-Za-z0-9_]", "_", x.lstrip("?"))


def rterm(x):
    if isinstance(x, str) and x.startswith("?"):
        return var(x)
    if isinstance(x, list):
        return None  # function terms in rules: not yet
    return term(x)


def atom(a):
    if not (isinstance(a, list) and a and isinstance(a[0], str)) or a[0] in CONNECTIVES or a[0].startswith("?"):
        return None
    args = [rterm(x) for x in a[1:]]
    if any(t is None for t in args):
        return None
    if a[0] in ("isa", "genls", "disjointWith") and len(args) == 2:
        x, y = (f"({t})" if t.startswith(".s ") else t for t in args)
        return f"(.{a[0]} {x} {y})"
    return f"(.atom (.c {lean_str(a[0])}) [{', '.join(args)}])"


def variables(a):
    out = []
    for x in a[1:]:
        if isinstance(x, str) and x.startswith("?") and var(x) not in out:
            out.append(var(x))
    return out


def main():
    zpath, out = sys.argv[1], Path(sys.argv[2])
    rules, skipped = [], collections.Counter()
    with zipfile.ZipFile(zpath) as z:
        for name in z.namelist():
            if not name.endswith(".krf"):
                continue
            mt = None
            for e in sexprs(z.read(name).decode("utf-8", errors="replace")):
                if isinstance(e, list) and e and e[0] == "in-microtheory" and len(e) > 1:
                    mt = e[1] if isinstance(e[1], str) else None
                    continue
                if not (isinstance(e, list) and len(e) == 3 and e[0] == "implies") or mt is None:
                    continue
                ante, concl = e[1], e[2]
                ants = ante[1:] if isinstance(ante, list) and ante and ante[0] == "and" else [ante]
                prem = [atom(a) for a in ants]
                c = atom(concl)
                if c is None or any(p is None for p in prem):
                    skipped["not Horn"] += 1
                    continue
                pv = [v for a in ants for v in variables(a)]
                if not set(variables(concl)) <= set(pv):
                    skipped["conclusion variable not in premises"] += 1
                    continue
                vs = list(dict.fromkeys(pv))
                rules.append((mt, vs, prem, c))
    path = out / "CycRules.lean"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("import Cyc.Rules\n\n/-! OpenCyc's Horn rules (NextKB), each in force in its microtheory and every\n"
                "microtheory that inherits it. Generated by gen_rules.py. -/\n\nnamespace CycRules\nopen Cyc\n\n")
        for i, (mt, vs, prem, c) in enumerate(rules):
            binders = f" {{{' '.join(vs)} : Term}}" if vs else ""
            hyps = "".join(f"Holds m {p} → " for p in prem)
            prob = 80 if ".c " in c else 10  # a conclusion naming a constant matches few goals
            f.write(f"@[aesop unsafe {prob}% apply (rule_sets := [Cyc])]\naxiom r{i} {{m : Mt}}{binders} "
                    f"(_ : Sees m (.c {lean_str(mt)})) :\n    {hyps}Holds m {c}\n\n")
        f.write("end CycRules\n")
    print(f"gen_rules: {len(rules)} rules -> {path}; skipped: "
          + ", ".join(f"{k}={v}" for k, v in skipped.most_common()))


if __name__ == "__main__":
    main()

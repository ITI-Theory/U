"""Every equation of the programme, listed and classed, for the match with the Lean (ISS-128).

  python sherlock/equations.py lean     bld/sherlock/lean/EquationsData.lean (and a census on stdout)

The equations come from lib/format/equations-writer.lua (pandoc, source positions on) for the papers and books
in English, and from the registry's levels (their `equation` fields, which the app shows). The first class is
the master equation's operator, the sign ISS-126 asks about: Helmholtz (∇² + k²: k a wavenumber, oscillation),
screened (∇² - k²: k a mass, decay) and Klein-Gordon (∂ₜ²/v² - ∇² + k²: k a mass). Lean holds the witness for
each class (Fishing/Equations.lean); the census shows which documents use which.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

U = Path(__file__).resolve().parents[1]
OUT = U / "bld" / "sherlock" / "lean"
WRITER = U / "lib" / "format" / "equations-writer.lua"
LANG = re.compile(r"\.(de|fr|it|es)\.md$")


def sources() -> list[Path]:
    fs = sorted((U / "paper" / "soma").glob("*/*.md")) + sorted((U / "books" / "T-Theory").glob("**/*.md"))
    return [f for f in fs if not LANG.search(f.name) and "OBSOLETE" not in str(f) and f.name.upper() == f.name.upper()
            and not f.name.startswith(("README", "PAPER2_", "CHANGELOG"))]


def canon(tex: str) -> str:
    t = re.sub(r"\\(left|right|big|Big|bigg|Bigg)\b", "", tex)
    t = re.sub(r"\\[,;!:]|\\quad|\\qquad|~", "", t)
    t = re.sub(r"\^\{(\w)\}", r"^\1", t)
    return re.sub(r"\s+", "", t)


OP = re.compile(r"(-?)\\nabla\^2([+-])(k|m|\\kappa|\\mu)(?:_\w|_\{[^}]*\}|\([^)]*\))?\^2")


FAMILIES = [  # the catches of the fishing, found again wherever an equation repeats them (ISS-126)
    ("kramers-no-friction", re.compile(r"\\frac\{2\\pi\}\{\\omega_\{?A\}?\\omega_\{?B\}?\}"), "\\gamma"),
    ("wkb-no-mass", re.compile(r"\\int[^=]*\\sqrt\{(V|U)\(q\)-E\}"), "2m"),
    ("omega-7-11", re.compile(r"\\Omega_\{?\\Lambda\}?(=|\\approx)(7/11|\\frac\{7\}\{11\}|\\tfrac\{7\}\{11\})"), None),
]


def classify(tex: str) -> str:
    c = canon(tex)
    for name, pat, unless in FAMILIES:
        if pat.search(c) and not (unless and unless in c):
            return name
    m = OP.search(c)
    if not m:
        return ""
    lead, sign = m.group(1), m.group(2)
    if lead == "-" and sign == "+":
        return "klein-gordon" if re.search(r"\\partial_t\^2|\\partial_\{t\}\^2|\\Box|\\frac\{1\}\{[^}]*\}\\partial|\\partial\^2\}\{\\partial(t|\\tau)\^2\}|v(_s)?\^\{?-2\}?\\partial", c) else "screened"
    if lead == "" and sign == "-":
        return "screened"
    if lead == "" and sign == "+":
        return "helmholtz"
    return "screened"


def extract(f: Path) -> list[dict]:
    try:
        r = subprocess.run(["pandoc", "-f", "commonmark_x+sourcepos", "-t", str(WRITER), str(f)],
                           capture_output=True, text=True, encoding="utf-8", timeout=120)
        return json.loads(r.stdout or "[]")
    except (subprocess.TimeoutExpired, json.JSONDecodeError):
        return []


def s(x) -> str:
    return '"' + str(x).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


CLASS_OF = {"Fishing.Gravity.wave_solves": "helmholtz", "Fishing.Gravity.yukawa_solves": "screened",
            "Fishing.KleinGordon.dispersion": "klein-gordon", "Fishing.KaluzaKlein.kk_reduction": "klein-gordon",
            "Fishing.KaluzaKlein.two_signs": "helmholtz", "Fishing.Kramers.narrower_faster": "kramers-no-friction",
            "Fishing.WKB.cheatsheet_drops_mass": "wkb-no-mass", "Fishing.Cosmology.published_misses": "omega-7-11"}


def report(lean_out: str) -> int:
    """The document's forms of the master equation beside the Lean's, by class (bld/sherlock/equations.md)."""
    latex = re.findall(r"LATEX (\S+) := (.*)", lean_out)
    data = (OUT / "EquationsData.lean").read_text(encoding="utf-8")
    rows = re.findall(r'\("([^"]+)", (\d+), \w+, "((?:[^"\\]|\\.)*)", "([a-z0-9-]+)"\)', data)
    out = ["# The master equation: the documents beside the Lean (ISS-128)", "",
           "Generated by `make -C sherlock equations`. Each class: the Lean that witnesses it, rendered back to LaTeX",
           "(`#latex`), then every document that writes that form, with its line.", ""]
    for cls in ("helmholtz", "klein-gordon", "screened", "kramers-no-friction", "wkb-no-mass", "omega-7-11"):
        out += [f"## {cls}", ""]
        out += [f"- Lean `{n}`: ${tex.strip()}$" for n, tex in latex if CLASS_OF.get(n) == cls] or ["- Lean: none"]
        out += [""] + [f"- {f}:{ln}: ${tx.replace(chr(92) * 2, chr(92))}$" for f, ln, tx, c in rows if c == cls] + [""]
    (OUT.parent / "equations.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"equations report: {len(latex)} Lean statements, {len(rows)} document forms -> {OUT.parent / 'equations.md'}")
    return 0


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    if len(sys.argv) > 1 and sys.argv[1] == "report":
        return report(sys.stdin.read())
    rows = []
    for f in sources():
        for e in extract(f):
            if e.get("display") or classify(e["tex"]):
                rows.append((f.relative_to(U).as_posix(), e.get("line", 0), bool(e.get("display")), e["tex"], classify(e["tex"])))
    for p in sorted((U / "registry" / "levels").glob("*.yaml")):
        y = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
        for key, tex in (("equation", y.get("equation")), ("equation_setting", (y.get("atlas_rows") or {}).get("equation_setting"))):
            if tex:
                rows.append((p.relative_to(U).as_posix() + "#" + key, 0, True, tex, classify(tex)))
    L = ["/-! Generated by sherlock/equations.py: the programme's equations (ISS-128). -/", "", "namespace EquationsData", "",
         "/-- (file, line, display, TeX, the master equation's class or \"\"). -/",
         "def all : List (String × Nat × Bool × String × String) := ["]
    L.append(",\n".join(f"  ({s(a)}, {b}, {'true' if c else 'false'}, {s(d[:300])}, {s(e)})" for a, b, c, d, e in rows))
    L += ["]", "", "end EquationsData", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "EquationsData.lean").write_text("\n".join(L), encoding="utf-8", newline="\n")
    cls = {}
    for a, b, c, d, e in rows:
        if e:
            cls.setdefault(e, set()).add(a.split("#")[0])
    print(f"equations: {len(rows)} ({sum(1 for r in rows if r[2])} display) in {len({r[0].split('#')[0] for r in rows})} sources")
    for k, v in sorted(cls.items()):
        print(f"  {k}: {sum(1 for r in rows if r[4] == k)} in {len(v)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
